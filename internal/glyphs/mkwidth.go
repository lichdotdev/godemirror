//go:build ignore

// mkwidth writes widetable.go, the code points Width gives two cells, from
// the Unicode Character Database: East Asian Width W and F (EastAsianWidth.txt,
// with the unassigned blocks its header defaults to W) and Emoji_Presentation
// (emoji-data.txt).
// Marks and format characters (by Go's unicode tables) are left out: they take
// no cell of their own, and the view gives them one rather than two.
//
//	go generate ./internal/glyphs
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

// unicodeVersion is the UCD release the table is cut from.
const unicodeVersion = "18.0.0"

const base = "https://www.unicode.org/Public/" + unicodeVersion + "/ucd/"

// wideByDefault is what EastAsianWidth.txt's header, not its lines, makes W:
// the unassigned code points of these ranges. Every assigned one is W too.
var wideByDefault = [][2]rune{{0x3400, 0x4DBF}, {0x4E00, 0x9FFF}, {0xF900, 0xFAFF}, {0x20000, 0x2FFFD}, {0x30000, 0x3FFFD}}

func main() {
	wide := map[rune]bool{}
	for _, rg := range wideByDefault {
		for r := rg[0]; r <= rg[1]; r++ {
			wide[r] = true
		}
	}
	read(base+"EastAsianWidth.txt", func(prop string) bool { return prop == "W" || prop == "F" }, wide)
	read(base+"emoji/emoji-data.txt", func(prop string) bool { return prop == "Emoji_Presentation" }, wide)
	var runes []rune
	for r := range wide {
		if !unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf) {
			runes = append(runes, r)
		}
	}
	slices.Sort(runes)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by mkwidth.go from Unicode %s; DO NOT EDIT.\n\n", unicodeVersion)
	b.WriteString("package glyphs\n\n// wide is the inclusive ranges of code points Width gives two cells.\nvar wide = [][2]rune{\n")
	ranges := 0
	for i := 0; i < len(runes); {
		j := i
		for j+1 < len(runes) && runes[j+1] == runes[j]+1 {
			j++
		}
		fmt.Fprintf(&b, "\t{%#04x, %#04x},\n", runes[i], runes[j])
		ranges++
		i = j + 1
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("widetable.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d code points in %d ranges", len(runes), ranges)
}

// read adds to set every code point of url's "range ; property" lines whose
// property keep accepts.
func read(url string, keep func(string) bool, set map[rune]bool) {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	s := bufio.NewScanner(resp.Body)
	for s.Scan() {
		line, _, _ := strings.Cut(s.Text(), "#")
		cps, prop, ok := strings.Cut(line, ";")
		if !ok || !keep(strings.TrimSpace(prop)) {
			continue
		}
		lo, hi, isRange := strings.Cut(strings.TrimSpace(cps), "..")
		if !isRange {
			hi = lo
		}
		for r := parse(lo); r <= parse(hi); r++ {
			set[r] = true
		}
	}
	if err := s.Err(); err != nil {
		log.Fatal(err)
	}
}

func parse(hex string) rune {
	n, err := strconv.ParseUint(hex, 16, 32)
	if err != nil {
		log.Fatalf("code point %q: %v", hex, err)
	}
	return rune(n)
}
