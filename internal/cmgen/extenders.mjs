// extenders.mjs writes extenders_generated.go: the code points
// @marijn/find-cluster-break, the package @codemirror/state finds grapheme
// cluster breaks with, counts as extending characters, as ranges. A dev tool,
// run with the node_modules directory state.mjs takes:
//
//	node internal/cmgen/extenders.mjs "$CODEMIRROR_NODE_MODULES" extenders_generated.go

import { writeFileSync } from "node:fs";
import { load, packageJSON } from "../lezer/gen/load.mjs";

const [modulesDir, out] = process.argv.slice(2);
const { isExtendingChar } = await load(modulesDir, "@marijn/find-cluster-break");
const version = packageJSON(modulesDir, "@marijn/find-cluster-break").version;

let ranges = [];
for (let code = 0, start = -1; code <= 0x110000; code++) {
  let ext = code < 0x110000 && isExtendingChar(code);
  if (ext && start < 0) start = code;
  else if (!ext && start >= 0) { ranges.push([start, code]); start = -1; }
}
const hex = (n) => "0x" + n.toString(16);
let lines = ranges.map(([from, to]) => `\t{${hex(from)}, ${hex(to)}},`);
writeFileSync(out, `// Code generated by internal/cmgen/extenders.mjs from @marijn/find-cluster-break ${version}; DO NOT EDIT.

package godemirror

// extenders are the code points [from, to) that extend the grapheme cluster
// before them.
var extenders = [][2]rune{
${lines.join("\n")}
}
`);
